// vanguard fix — turn fixable findings into exact remediation commands.
//
// For each finding with a known fixed version (fix.patch_ref), it prints the
// precise OS-package upgrade command. It is dry-run by default: it never runs
// apt, so it is safe on a shared box. Use -script to emit a reviewable shell
// script, then run it yourself with sudo.
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/Pentatonic-Labs/vanguard/findings"
)

func runFix(args []string) {
	fs := flag.NewFlagSet("fix", flag.ExitOnError)
	dataDir := fs.String("data-dir", findings.DefaultDataDir, "findings data dir")
	script := fs.String("script", "", "write remediation commands to a shell script (reviewable, then sudo)")
	fs.Parse(args)

	list, err := findings.Load(*dataDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "vanguard:", err)
		os.Exit(1)
	}

	type fixCmd struct{ summary, cmd string }
	var fixes []fixCmd
	for _, f := range list {
		if f.Fix == nil || f.Fix.PatchRef == "" {
			continue // no known fixed version — nothing to apply
		}
		cmd := fmt.Sprintf("apt-get install --only-upgrade %s=%s", f.Target.Ref, f.Fix.PatchRef)
		fixes = append(fixes, fixCmd{summary: f.Vuln.Summary, cmd: cmd})
	}
	sort.Slice(fixes, func(i, j int) bool { return fixes[i].cmd < fixes[j].cmd })

	if len(fixes) == 0 {
		fmt.Println("no findings with a known fixed version to apply")
		return
	}

	if *script != "" {
		var b strings.Builder
		b.WriteString("#!/bin/sh\nset -e\n# generated by `vanguard fix` — review before running (sudo).\n")
		for _, fx := range fixes {
			b.WriteString("# " + fx.summary + "\n")
			b.WriteString(fx.cmd + "\n")
		}
		if err := os.WriteFile(*script, []byte(b.String()), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "vanguard:", err)
			os.Exit(1)
		}
		fmt.Printf("wrote %d remediation command(s) to %s (review, then run with sudo)\n", len(fixes), *script)
		return
	}

	fmt.Printf("%d fixable finding(s):\n\n", len(fixes))
	for _, fx := range fixes {
		fmt.Printf("%s\n  %s\n\n", fx.summary, fx.cmd)
	}
	fmt.Println("dry-run: nothing was changed. Run with -script to emit a shell script, or apply the commands manually with sudo.")
}
